import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
const project = resolve(import.meta.dirname, '..');
const output = join(project, 'web-dist');
const basePath = (process.env.FITNESS_WEB_BASE_PATH || '/Fitness').replace(/\/$/, '');
const result = spawnSync(process.platform === 'win32' ? 'npx.cmd' : 'npx', ['expo', 'export', '--platform', 'web', '--output-dir', 'web-dist'], {
  cwd: project, env: { ...process.env, FITNESS_WEB_BASE_PATH: basePath }, stdio: 'inherit', shell: process.platform === 'win32',
});
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status || 1);
mkdirSync(join(output, 'icons'), { recursive: true });
copyFileSync(join(project, 'assets/icon.png'), join(output, 'icons/icon.png'));
const manifest = {
  id: './', name: 'Дневник силы', short_name: 'Дневник силы', description: 'Упражнения, веса и повторы — ваш дневник тренировок.',
  lang: 'ru', start_url: './', scope: './', display: 'standalone', background_color: '#0C1225', theme_color: '#0C1225',
  icons: [{ src: 'icons/icon.png', sizes: '1024x1024', type: 'image/png', purpose: 'any' }],
};
writeFileSync(join(output, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2));
const apk = process.env.FITNESS_APK_PATH || join(project, 'artifacts/fitness-android.apk');
const apkAvailable = existsSync(apk);
let html = readFileSync(join(output, 'index.html'), 'utf8').replace('<html lang="en">', '<html lang="ru">');
const registration = `window.__fitnessAndroidApkUrl=${JSON.stringify(apkAvailable ? './downloads/fitness-android.apk' : null)};window.__fitnessInstallable=true;if('serviceWorker' in navigator){window.addEventListener('load',()=>{navigator.serviceWorker.register('./service-worker.js',{scope:'./'}).then(()=>navigator.serviceWorker.ready).then(()=>{window.__fitnessOfflineReady=true;window.dispatchEvent(new Event('fitness-offline-ready'));}).catch(()=>{window.dispatchEvent(new Event('fitness-offline-error'));});});}`;
html = html.replace('</head>', `<meta name="theme-color" content="#0C1225" />\n<meta name="apple-mobile-web-app-capable" content="yes" />\n<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />\n<meta name="apple-mobile-web-app-title" content="Дневник силы" />\n<link rel="apple-touch-icon" href="${basePath}/icons/icon.png" />\n<link rel="manifest" href="${basePath}/manifest.webmanifest" />\n<script>${registration}</script>\n</head>`);
writeFileSync(join(output, 'index.html'), html);
writeFileSync(join(output, '.nojekyll'), '');
writeFileSync(join(output, '.fitness-web-export'), 'Generated by Fitness offline web exporter v1\n');
function files(dir) { return readdirSync(dir, { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? files(join(dir, entry.name)) : [join(dir, entry.name)]); }
const precache = files(output).filter(p => !p.endsWith('service-worker.js') && !p.endsWith('.nojekyll'));
const hash = createHash('sha256');
for (const file of precache.sort()) hash.update(relative(output, file)).update(readFileSync(file));
const version = hash.digest('hex').slice(0, 16);
const assets = precache.map(file => './' + relative(output, file).split('\\').join('/'));
const worker = `const PREFIX='fitness-shell:'+new URL(self.registration.scope).pathname+':';
const CACHE=PREFIX+${JSON.stringify(version)};
const ASSETS=${JSON.stringify(assets)};
self.addEventListener('install',event=>{event.waitUntil(caches.open(CACHE).then(cache=>cache.addAll(ASSETS)));});
self.addEventListener('activate',event=>{event.waitUntil((async()=>{for(const key of await caches.keys()){if(key.startsWith(PREFIX)&&key!==CACHE)await caches.delete(key);}await self.clients.claim();})());});
self.addEventListener('fetch',event=>{
 const url=new URL(event.request.url);
 if(event.request.method!=='GET'||url.origin!==self.location.origin||!url.href.startsWith(self.registration.scope)||url.pathname.endsWith('.apk'))return;
 event.respondWith((async()=>{
  const cache=await caches.open(CACHE);
  if(event.request.mode==='navigate'){
   try{const response=await fetch(event.request);if(response.ok){await cache.put(new URL('./index.html',self.registration.scope),response.clone());return response;}}catch{}
   return (await cache.match(new URL('./index.html',self.registration.scope)))||Response.error();
  }
  const saved=await cache.match(event.request);if(saved)return saved;
  const response=await fetch(event.request);if(response.ok)await cache.put(event.request,response.clone());return response;
 })());
});
`;
writeFileSync(join(output, 'service-worker.js'), worker);
if (apkAvailable) {
  mkdirSync(join(output, 'downloads'), { recursive: true });
  copyFileSync(apk, join(output, 'downloads/fitness-android.apk'));
  const checksum = apk + '.sha256';
  if (existsSync(checksum)) copyFileSync(checksum, join(output, 'downloads/fitness-android.apk.sha256'));
}

console.log(`Installable offline web app built in web-dist for ${basePath || '/'}. Cache version: ${version}`);
