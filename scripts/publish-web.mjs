import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
const project = resolve(import.meta.dirname, '..');
const output = join(project, 'web-dist');
const marker = 'Generated by Fitness offline web exporter v1\n';
if (!existsSync(join(output, 'service-worker.js')) || readFileSync(join(output, '.fitness-web-export'), 'utf8') !== marker) throw new Error('Run npm run build:web before publishing.');
const git = (args, options = {}) => execFileSync('git', args, { cwd: project, encoding: 'utf8', ...options });
const remote = git(['ls-remote', '--heads', 'origin', 'refs/heads/gh-pages']).trim().split(/\s+/)[0];
let parent;
if (remote) {
  if (!/^[a-f0-9]{40}$/.test(remote)) throw new Error('Invalid remote commit');
  git(['fetch', '--no-tags', 'origin', 'refs/heads/gh-pages']);
  let previous;
  try { previous = git(['show', `${remote}:.fitness-web-export`]); } catch { throw new Error('Existing gh-pages branch is not a Fitness export; refusing to replace it.'); }
  if (previous !== marker) throw new Error('Existing gh-pages branch contains unrelated content.');
  parent = remote;
}
const directory = mkdtempSync(join(tmpdir(), 'fitness-pages-'));
try {
  const gitDir = git(['rev-parse', '--absolute-git-dir']).trim();
  const env = { ...process.env, GIT_INDEX_FILE: join(directory, 'index') };
  const stage = args => git([`--git-dir=${gitDir}`, `--work-tree=${output}`, ...args], { cwd: output, env });
  stage(['read-tree', '--empty']);
  stage(['add', '--force', '--all', '--', '.']);
  const tree = stage(['write-tree']).trim();
  const commit = git(['commit-tree', tree, ...(parent ? ['-p', parent] : []), '-m', 'Publish installable offline fitness app']).trim();
  git(['push', 'origin', `${commit}:refs/heads/gh-pages`], { stdio: 'inherit' });
  console.log('Static app pushed to gh-pages. Enable GitHub Pages from that branch and verify HTTPS before sharing the installation URL.');
} finally { rmSync(directory, { recursive: true, force: true }); }
